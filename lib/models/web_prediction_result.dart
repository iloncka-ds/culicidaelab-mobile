import 'dart:convert';

/// Represents the result of a web-based mosquito species prediction.
///
/// This model contains prediction results from remote classification services,
/// including species identification, confidence scores, probability distributions
/// across all possible species, and associated metadata. It's used when
/// classification is performed on external servers rather than locally on the device.
///
/// The prediction result includes comprehensive probability data for transparency
/// and supports both single-prediction and multi-class classification scenarios.
///
/// ## Usage Example
///
/// ```dart
/// // Typically received from API response
/// final result = WebPredictionResult(
///   id: 'pred_123456',
///   scientificName: 'Aedes aegypti',
///   probabilities: {
///     'Aedes aegypti': 0.87,
///     'Aedes albopictus': 0.08,
///     'Culex pipiens': 0.03,
///     'Anopheles gambiae': 0.02,
///   },
///   modelId: 'culico-net-cls-v1',
///   confidence: 0.87,
///   imageUrlSpecies: 'https://api.culicidaelab.org/species/aedes_aegypti.jpg',
/// );
///
/// print('Top prediction: ${result.scientificName}');
/// print('Confidence: ${result.confidencePercentage}');
/// print('Alternative species: ${result.alternativeSpecies}');
/// ```
///
/// ## Server Integration
///
/// This model is designed to work with the CulicidaeLab server API:
/// - Receives predictions from `/predict` endpoint
/// - Includes full probability distribution for transparency
/// - Supports model versioning and tracking
/// - Provides species image URLs for display
///
/// ## Comparison with Local Classification
///
/// Unlike [ClassificationResult] which is used for local PyTorch Lite predictions,
/// this model represents server-side classification results with additional
/// features like probability distributions and remote image URLs.
///
/// See also:
/// - [ClassificationResult] for local device-based predictions
/// - [Observation] for storing prediction results as observations
/// - CulicidaeLab server API documentation
class WebPredictionResult {
  /// Unique identifier for this prediction.
  ///
  /// Generated by the server to track individual prediction requests.
  /// Used for logging, debugging, and potential result caching.
  ///
  /// Example: `'pred_123456'`, `'uuid-4-format-string'`
  final String id;

  /// Scientific name of the predicted mosquito species.
  ///
  /// The species with the highest probability from the classification model.
  /// Follows binomial nomenclature conventions and matches species names
  /// used in [MosquitoSpecies] models.
  ///
  /// Example: `'Aedes aegypti'`, `'Anopheles gambiae'`
  final String scientificName;

  /// Probability distribution across all possible species.
  ///
  /// Maps species scientific names to their prediction probabilities.
  /// All values sum to 1.0, providing complete transparency about
  /// the model's decision-making process.
  ///
  /// Example:
  /// ```dart
  /// {
  ///   'Aedes aegypti': 0.87,
  ///   'Aedes albopictus': 0.08,
  ///   'Culex pipiens': 0.03,
  ///   'Anopheles gambiae': 0.02,
  /// }
  /// ```
  final Map<String, double> probabilities;

  /// Identifier of the AI model used for prediction.
  ///
  /// References the specific version of the classification model
  /// deployed on the server. Important for tracking model performance,
  /// comparing results, and ensuring reproducibility.
  ///
  /// Example: `'culico-net-cls-v1'`, `'exp_7_new_bg_simple-subs_1_v_5'`
  final String modelId;

  /// Confidence score of the top prediction (0.0 to 1.0).
  ///
  /// Represents the model's confidence in the species identification.
  /// This is typically the same as the highest probability in the
  /// probabilities map, but may be calculated differently by some models.
  final double confidence;

  /// Optional URL to the species reference image.
  ///
  /// Server-provided URL to a reference image of the predicted species.
  /// Used for displaying species information and helping users
  /// verify the identification result.
  ///
  /// Example: `'https://api.culicidaelab.org/species/aedes_aegypti.jpg'`
  final String? imageUrlSpecies;

  /// Creates a new [WebPredictionResult] instance.
  ///
  /// All required parameters must be provided to ensure complete
  /// prediction information is available.
  ///
  /// Throws [ArgumentError] if validation fails.
  WebPredictionResult({
    required this.id,
    required this.scientificName,
    required this.probabilities,
    required this.modelId,
    required this.confidence,
    this.imageUrlSpecies,
  }) : assert(id.isNotEmpty, 'Prediction ID cannot be empty'),
       assert(scientificName.isNotEmpty, 'Scientific name cannot be empty'),
       assert(modelId.isNotEmpty, 'Model ID cannot be empty'),
       assert(confidence >= 0.0 && confidence <= 1.0,
              'Confidence must be between 0.0 and 1.0'),
       assert(probabilities.isNotEmpty, 'Probabilities cannot be empty'),
       assert(_validateProbabilities(probabilities),
              'Probabilities must sum to approximately 1.0');

  /// Validates that probabilities sum to approximately 1.0.
  static bool _validateProbabilities(Map<String, double> probabilities) {
    final sum = probabilities.values.fold(0.0, (a, b) => a + b);
    return (sum - 1.0).abs() < 0.01; // Allow small floating-point errors
  }

  /// Creates a [WebPredictionResult] from a JSON map.
  ///
  /// Used for deserializing prediction results from API responses.
  /// Handles the conversion of probability values to ensure they are doubles.
  ///
  /// Example:
  /// ```dart
  /// final json = {
  ///   'id': 'pred_123',
  ///   'scientific_name': 'Aedes aegypti',
  ///   'probabilities': {
  ///     'Aedes aegypti': 0.87,
  ///     'Aedes albopictus': 0.08,
  ///   },
  ///   'model_id': 'culico-net-cls-v1',
  ///   'confidence': 0.87,
  /// };
  /// final result = WebPredictionResult.fromJson(json);
  /// ```
  factory WebPredictionResult.fromJson(Map<String, dynamic> json) {
    return WebPredictionResult(
      id: json['id'] as String,
      scientificName: json['scientific_name'] as String,
      // Safely cast the map values to double
      probabilities: (json['probabilities'] as Map<String, dynamic>).map(
        (key, value) => MapEntry(key, (value as num).toDouble()),
      ),
      modelId: json['model_id'] as String,
      confidence: (json['confidence'] as num).toDouble(),
      imageUrlSpecies: json['image_url_species'] as String?,
    );
  }

  /// Creates a [WebPredictionResult] from a JSON string.
  ///
  /// Convenience method for parsing JSON strings directly from API responses.
  ///
  /// Example:
  /// ```dart
  /// final jsonString = '{"id": "pred_123", "scientific_name": "Aedes aegypti", ...}';
  /// final result = WebPredictionResult.fromJsonString(jsonString);
  /// ```
  static WebPredictionResult fromJsonString(String str) =>
      WebPredictionResult.fromJson(json.decode(str));

  /// Converts this [WebPredictionResult] to a JSON map.
  ///
  /// Used for serializing prediction results for storage or further processing.
  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'scientific_name': scientificName,
      'probabilities': probabilities,
      'model_id': modelId,
      'confidence': confidence,
      if (imageUrlSpecies != null) 'image_url_species': imageUrlSpecies,
    };
  }

  /// Gets the confidence as a percentage string.
  ///
  /// Returns a formatted string representation of the confidence
  /// score as a percentage with one decimal place.
  ///
  /// Example: `'87.3%'` for confidence of 0.873
  String get confidencePercentage =>
      '${(confidence * 100).toStringAsFixed(1)}%';

  /// Checks if the prediction has high confidence.
  ///
  /// Returns `true` if confidence is 0.7 or higher, indicating
  /// a reliable identification that can be presented to users
  /// with confidence.
  bool get isHighConfidence => confidence >= 0.7;

  /// Gets a human-readable confidence level description.
  ///
  /// Returns a descriptive string based on the confidence score:
  /// - 'Very High' for 0.9+
  /// - 'High' for 0.7-0.9
  /// - 'Moderate' for 0.5-0.7
  /// - 'Low' for below 0.5
  String get confidenceLevel {
    if (confidence >= 0.9) return 'Very High';
    if (confidence >= 0.7) return 'High';
    if (confidence >= 0.5) return 'Moderate';
    return 'Low';
  }

  /// Gets the top N alternative species predictions.
  ///
  /// Returns a list of species names sorted by probability (excluding the top prediction).
  /// Useful for showing users alternative possibilities when confidence is moderate.
  ///
  /// Example:
  /// ```dart
  /// final alternatives = result.getTopAlternatives(3);
  /// // ['Aedes albopictus', 'Culex pipiens', 'Anopheles gambiae']
  /// ```
  List<String> getTopAlternatives([int count = 3]) {
    final sorted = probabilities.entries.toList()
      ..sort((a, b) => b.value.compareTo(a.value));
    
    return sorted
        .skip(1) // Skip the top prediction
        .take(count)
        .map((entry) => entry.key)
        .toList();
  }

  /// Gets alternative species with their probabilities.
  ///
  /// Returns a map of alternative species (excluding the top prediction)
  /// with their probability scores, sorted by probability.
  Map<String, double> get alternativeSpecies {
    final alternatives = Map<String, double>.from(probabilities);
    alternatives.remove(scientificName);
    
    final sorted = alternatives.entries.toList()
      ..sort((a, b) => b.value.compareTo(a.value));
    
    return Map.fromEntries(sorted);
  }

  /// Gets the probability of the predicted species.
  ///
  /// Returns the probability score for the top predicted species.
  /// This should typically match the confidence score.
  double get topProbability => probabilities[scientificName] ?? 0.0;

  /// Checks if there are close alternative predictions.
  ///
  /// Returns `true` if there's another species with probability within
  /// 0.2 of the top prediction, indicating potential ambiguity.
  bool get hasCloseAlternatives {
    final alternatives = alternativeSpecies;
    if (alternatives.isEmpty) return false;
    
    final topAlternative = alternatives.values.first;
    return (topProbability - topAlternative) < 0.2;
  }

  /// Returns a string representation of this prediction result.
  ///
  /// Primarily used for debugging and logging purposes.
  @override
  String toString() {
    return 'WebPredictionResult('
           'id: $id, '
           'species: $scientificName, '
           'confidence: $confidencePercentage, '
           'modelId: $modelId)';
  }

  /// Checks if two [WebPredictionResult] instances are equal.
  ///
  /// Two results are considered equal if they have the same ID.
  @override
  bool operator ==(Object other) {
    if (identical(this, other)) return true;
    return other is WebPredictionResult && other.id == id;
  }

  /// Returns the hash code for this prediction result.
  ///
  /// Based on the prediction ID for consistent hashing.
  @override
  int get hashCode => id.hashCode;
}